def cmd_doctor(store, args):
    p = store.events_path
    if args.fix_trailing:
        with store.lock():
            raw = p.read_bytes()
            if raw and not raw.endswith(b"\n"):
                keep = raw[: raw.rfind(b"\n") + 1]
                shutil.copy2(p, p.with_suffix(".jsonl.bak"))
                p.write_bytes(keep)
                print(f"dropped a {len(raw) - len(keep)}-byte partial final line (backup: events.jsonl.bak)")
            else:
                print("nothing to fix")
        return
    try:
        cfg, events, st = load(store)
    except LearnError as e:
        print(f"PROBLEM: {e}")
        print("Fix: if it is the last line and partial → `doctor --fix-trailing`. Otherwise open events.jsonl, "
              "look at that line, and restore it from a backup snapshot. Never edit other lines.")
        sys.exit(1)
    problems = []
    ids = set()
    for ev in events:
        if ev["id"] in ids:
            problems.append(f"duplicate event id {ev['id']}")
        ids.add(ev["id"])
    for it in st["items"].values():
        if it["state"] == "active" and activation_problems(it):
            problems.append(f"active item {it['item_id']} fails activation rules: {activation_problems(it)}")
    lock = store.lock_path.exists()
    out({"events": len(events), "concepts": len(st["concepts"]), "items": len(st["items"]),
         "problems": problems, "lock_present": lock})


