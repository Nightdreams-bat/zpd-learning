def kill_tree(proc):
    if os.name == "nt":
        subprocess.run(["taskkill", "/PID", str(proc.pid), "/T", "/F"], capture_output=True)
    else:
        try:
            os.killpg(proc.pid, 9)
        except Exception:
            proc.kill()


def run_tests(tests: dict, solution: Path, timeout=10.0) -> tuple[str, str]:
    """Run pinned pytest file against the submitted solution in a fresh temp dir.
    Returns (pass|fail|infra_error, output tail). infra_error never grades."""
    tf = Path(tests["test_file"]).expanduser()
    if not tf.exists():
        return "infra_error", f"test file missing: {tf}"
    if hashlib.sha256(tf.read_bytes()).hexdigest() != tests.get("test_sha256"):
        return "infra_error", "test file hash mismatch (tests changed since the item was verified)"
    if not solution.exists():
        return "infra_error", f"solution file missing: {solution}"
    work = Path(tempfile.mkdtemp(prefix="learn-check-"))
    try:
        shutil.copy(solution, work / tests.get("entry", "solution.py"))
        shutil.copy(tf, work / tf.name)
        for fx in tests.get("fixtures", []):
            shutil.copy(Path(fx).expanduser(), work / Path(fx).name)
        kw = {"creationflags": subprocess.CREATE_NEW_PROCESS_GROUP} if os.name == "nt" else {"start_new_session": True}
        proc = subprocess.Popen([sys.executable, "-m", "pytest", "-q", "-p", "no:cacheprovider", tf.name],
                                cwd=work, stdout=subprocess.PIPE, stderr=subprocess.STDOUT, text=True, **kw)
        try:
            outp, _ = proc.communicate(timeout=timeout)
        except subprocess.TimeoutExpired:
            kill_tree(proc)
            proc.communicate()
            return "fail", f"timed out after {timeout:.0f}s (whole process tree killed)"
        tail = "\n".join(outp.strip().splitlines()[-15:])
        if proc.returncode == 0:
            return "pass", tail
        if proc.returncode == 1:
            return "fail", tail
        return "infra_error", f"pytest exit {proc.returncode}: {tail}"
    finally:
        shutil.rmtree(work, ignore_errors=True)


def cmd_check(store, args):
    def fn(cfg, events, st):
        a = st["attempts"].get(args.id)
        if not a or not a["item_id"]:
            raise LearnError("unknown attempt or attempt has no item")
        it = st["items"][a["item_id"]]
        if not it.get("tests"):
            raise LearnError("item has no tests")
        res, tail = run_tests(it["tests"], Path(args.solution))
        cmd_check.result = (res, tail)
        return [{"type": "check", "attempt_id": args.id, "result": res, "output": tail,
                 "solution_sha256": hashlib.sha256(Path(args.solution).read_bytes()).hexdigest()
                 if Path(args.solution).exists() else None}]
    mutate(store, fn)
    res, tail = cmd_check.result
    out({"result": res, "output": tail})


def cmd_check_item(store, args):
    """Author-time validation: reference must pass, stub must fail. Records the test hash on the item."""
    def fn(cfg, events, st):
        it = st["items"].get(args.item)
        if not it or not it.get("tests"):
            raise LearnError("unknown item or no tests")
        tests = dict(it["tests"])
        tests["test_sha256"] = hashlib.sha256(Path(tests["test_file"]).expanduser().read_bytes()).hexdigest()
        r1, t1 = run_tests(tests, Path(args.reference))
        r2, t2 = run_tests(tests, Path(args.stub))
        cmd_check_item.result = {"reference": r1, "stub": r2, "reference_out": t1, "stub_out": t2}
        tests["reference_passed"] = r1 == "pass"
        tests["stub_failed"] = r2 == "fail"
        return [{"type": "item_revise", "item_id": args.item, "fields": {"tests": tests},
                 "reason": "check-item"}]
    mutate(store, fn)
    out(cmd_check_item.result)


