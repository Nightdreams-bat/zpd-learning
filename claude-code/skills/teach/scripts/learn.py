def load(store: Store):
    store.require()
    cfg = store.config()
    events = store.read_events()
    return cfg, events, replay(events, cfg)


def write_cache(store: Store, cfg, st):
    at = now_utc()
    brief = {"generated": iso(at), "items": {}, "lessons": st["lessons"], "checkpoint_due": checkpoint_due(st, cfg, at),
             "pending": [a["attempt_id"] for a in st["attempts"].values()
                         if a["answered_at"] and not a["grade"] and not a["abandoned"]]}
    for iid, it in st["items"].items():
        ed = effective_due(it, cfg)
        brief["items"][iid] = {"state": it["state"], "type": it["type"],
                               "due": iso(ed) if ed else None, "reviews": it["reviews"]}
    brief["est_minutes"] = cfg["est_minutes"]
    brief["rollover_hour"] = cfg["rollover_hour"]
    brief["timezone"] = cfg["timezone"]
    atomic_write(store.state_path, json.dumps(brief, indent=1, ensure_ascii=False))


def mutate(store: Store, fn):
    """Run fn(cfg, events, state) -> list[events] under the lock, append, refresh the cache."""
    with store.lock():
        cfg, events, st = load(store)
        new = fn(cfg, events, st) or []
        if new:
            # validate the result replays before committing it
            for ev in new:
                ev.setdefault("id", new_id("e"))
                ev.setdefault("ts", iso(now_utc()))
            st2 = replay(events + new, cfg)
            store.append(new)
            write_cache(store, cfg, st2)
            return new, st2
        return new, st


def out(obj):
    print(json.dumps(obj, indent=2, ensure_ascii=False, default=str))


