def compute_stats(st, cfg, at=None):
    at = at or now_utc()
    graded = [a for a in st["attempts"].values() if a["grade"] and a["grade"]["outcome"] != "ungradable"]
    sched = [a for a in graded if a["kind"] == "scheduled" and not a["assisted"]]
    retention = (sum(a["grade"]["rating"] != "again" for a in sched), len(sched))
    cold = []
    for it in st["items"].values():
        if it["type"] in ("problem", "mistake"):
            for h in it["history"]:
                if h["elapsed_days"] is not None and h["elapsed_days"] >= 30:
                    cold.append(h["ok"])
    cps = []
    for cp in st["checkpoints"]:
        atts = [a for a in graded if a.get("session") == cp["session_id"]]
        cps.append({"session": cp["session_id"], "date": cp["ts"][:10], "n": len(atts),
                    "correct": sum(a["grade"]["outcome"] == "correct" and not a["assisted"] for a in atts),
                    "sampled": len(cp["sampled"]), "eligible": cp.get("eligible")})
    stage_counts = [0] * 5
    for c in st["concepts"].values():
        stage_counts[c["stage"]] += 1
    today_end = day_end_utc(local_day(at, cfg), cfg)
    due = [it for it in st["items"].values() if it["state"] == "active" and it["reviews"] > 0
           and effective_due(it, cfg) <= today_end]
    overdue = [it for it in due if effective_due(it, cfg) < today_end - timedelta(days=1)]
    states = {}
    for it in st["items"].values():
        states[it["state"]] = states.get(it["state"], 0) + 1
    return {"checkpoints": cps, "retention": retention,
            "cold_resolve_30d": (sum(cold), len(cold)), "stages": stage_counts, "due": len(due),
            "overdue": len(overdue), "item_states": states,
            "pending": sum(1 for a in st["attempts"].values() if a["answered_at"] and not a["grade"] and not a["abandoned"])}


def pct(pair):
    k, n = pair
    return f"{k}/{n} ({100 * k / n:.0f}%)" if n else "— (no data yet)"


