def cmd_lesson(store, args):
    if args.action == "start":
        def fn(cfg, events, st):
            return [{"type": "lesson_start", "lesson_id": args.id or new_id("l"), "area": args.area, "path": args.path}]
        new, _ = mutate(store, fn)
        out({"lesson_id": new[0]["lesson_id"]})
    elif args.action == "finalize":
        def fn(cfg, events, st):
            les = st["lessons"].get(args.id)
            if not les:
                raise LearnError(f"unknown lesson {args.id}")
            evs, blocked = [], []
            for it in st["items"].values():
                if it.get("lesson_id") == args.id and it["state"] == "draft":
                    p = activation_problems(it)
                    if p:
                        blocked.append(f"{it['item_id']}: {p}")
                    else:
                        evs.append({"type": "item_state", "item_id": it["item_id"], "state": "active",
                                    "reason": "lesson finalize"})
            if blocked:
                raise LearnError("cannot finalize — fix these drafts first:\n  " + "\n  ".join(blocked))
            if les["finalized"] is None:
                evs.append({"type": "lesson_finalize", "lesson_id": args.id})
            return evs
        new, _ = mutate(store, fn)
        out({"activated": [e["item_id"] for e in new if e["type"] == "item_state"]})


