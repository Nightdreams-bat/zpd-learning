ROW = re.compile(r"^\|(.+)\|\s*$")


def parse_v2_tracker(path: Path):
    rows, notes, header = [], {}, None
    cur = None
    for line in path.read_text(encoding="utf-8").splitlines():
        m = ROW.match(line)
        if m and "---" not in line:
            cells = [c.strip() for c in m.group(1).split("|")]
            if header is None:
                header = [h.lower() for h in cells]
                continue
            if len(cells) == len(header):
                rows.append(dict(zip(header, cells)))
            continue
        b = re.match(r"^\*\*(.+?)\*\*\s*$", line.strip())
        if b:
            cur = b.group(1)
            notes[cur] = []
        elif cur and line.strip().startswith("-"):
            notes[cur].append(line.strip()[1:].strip())
    return rows, notes


def learned_at(x):
    d = (x["legacy"].get("last tested") or "").strip()
    return {"learned_at": d} if re.fullmatch(r"\d{4}-\d{2}-\d{2}", d) else {}


def cmd_migrate(store, args):
    cdir = store.vault / "concepts"
    files = sorted(p for p in cdir.glob("*.md"))
    plan = []
    for p in files:
        area = p.stem
        rows, notes = parse_v2_tracker(p)
        lessons = sorted((store.vault / area).glob("*.md")) if (store.vault / area).exists() else []
        for r in rows:
            name = r.get("concept", "").strip()
            if not name:
                continue
            stage_txt = r.get("stage", "")
            stage = int(stage_txt[0]) if stage_txt[:1].isdigit() else (2 if r.get("status") == "🟢" else 1)
            words = [w for w in re.findall(r"[a-zA-Z]{5,}", name.lower())][:4]
            lesson = None
            for lp in lessons:
                txt = lp.read_text(encoding="utf-8", errors="ignore").lower()
                if words and sum(w in txt for w in words) >= max(1, len(words) - 1):
                    lesson = f"{area}/{lp.name}"
                    break
            plan.append({"area": area, "name": name, "stage": stage, "lesson": lesson,
                         "legacy": {k: r.get(k) for k in ("attempts", "correct", "last tested", "next review", "status")},
                         "error_notes": notes.get(name, [])})
    if args.dry_run:
        out({"concept_files": [p.name for p in files], "concepts": len(plan),
             "with_lesson_link": sum(1 for x in plan if x["lesson"]), "sample": plan[:3]})
        return

    def fn(cfg, events, st):
        evs = []
        for x in plan:
            cid = slug(x["area"] + "-" + x["name"])
            if cid in st["concepts"] or any(e.get("concept_id") == cid and e["type"] == "concept_add" for e in evs):
                continue
            evs.append({"type": "concept_add", "concept_id": cid, "area": x["area"], "name": x["name"],
                        "lesson": x["lesson"], "stage": x["stage"], "legacy": x["legacy"]})
            evs.append({"type": "item_add", "item_id": new_id("i"), "concept_id": cid, "item_type": "concept",
                        "state": "draft", "area": x["area"], "source": "v2-migration",
                        "rubric_hints": x["error_notes"], **learned_at(x)})
        return evs

    archive = cdir / "_v2-archive"
    archive.mkdir(exist_ok=True)
    for p in files:
        shutil.copy2(p, archive / p.name)
    new, st = mutate(store, fn)
    for p in files:
        p.unlink()
    cfg = store.config()
    render(store, cfg, st)
    out({"migrated_concepts": sum(e["type"] == "concept_add" for e in new), "archived_to": str(archive)})


