def render_area(store, cfg, st, area, cs):
    lines = [f"# {area} — Concept Tracker", "",
             "> Generated by `learn.py render` — do not edit by hand.", "",
             "| Concept | Stage | Items (active/draft) | Reviews | Last review | Next due | Status |",
             "|---|---|---|---|---|---|---|"]
    notes = []
    for c in sorted(cs, key=lambda c: c["created"]):
        its = [it for it in st["items"].values() if it["concept_id"] == c["concept_id"]]
        act = sum(it["state"] == "active" for it in its)
        dr = sum(it["state"] == "draft" for it in its)
        revs = sum(it["reviews"] for it in its)
        last = max((it["last_review"] for it in its if it["last_review"]), default=None)
        dues = [effective_due(it, cfg) for it in its if it["state"] == "active"]
        nd = min(dues).astimezone(tz(cfg)).strftime("%Y-%m-%d") if dues else "—"
        last_ok = None
        for it in its:
            if it["history"]:
                last_ok = it["history"][-1]["ok"]
        status = "⬜" if last_ok is None else ("🟢" if last_ok else "🔴")
        if any(it["state"] == "suspended" for it in its):
            status += " ⏸"
        lines.append(f"| {c['name']} | {STAGES[c['stage']]} | {act}/{dr} | {revs} | {(last or '—')[:10]} | {nd} | {status} |")
        if c["errors"]:
            notes.append(f"**{c['name']}**")
            for e in c["errors"][-3:]:
                notes.append(f"- {e['ts'][:10]} ({e['kind']}): {e['note']}")
            notes.append("")
    lines += ["", "### Error Notes", ""] + (notes or ["(none yet)"])
    atomic_write(store.vault / "concepts" / f"{area}.md", "\n".join(lines) + "\n")


