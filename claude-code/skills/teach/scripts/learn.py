def cmd_attempt(store, args):
    if args.action == "start":
        def fn(cfg, events, st):
            it = st["items"].get(args.item) if args.item else None
            if args.item and not it:
                raise LearnError(f"unknown item {args.item}")
            kind = args.kind
            if kind in FSRS_KINDS:
                if not it:
                    raise LearnError(f"{kind} attempts need --item")
                if it["state"] != "active":
                    raise LearnError(f"item {args.item} is {it['state']}, not active")
                for a in st["attempts"].values():
                    if a["item_id"] == args.item and not a["grade"] and not a["abandoned"] and a["kind"] in FSRS_KINDS:
                        raise LearnError(f"item already has an open attempt {a['attempt_id']} — answer, grade or abandon it")
            cid = it["concept_id"] if it else args.concept
            if cid not in st["concepts"]:
                raise LearnError("attempt needs --item or a known --concept")
            return [{"type": "attempt_start", "attempt_id": new_id("a"), "item_id": args.item, "concept_id": cid,
                     "kind": kind, "item_rev": it["rev"] if it else None, "session": args.session,
                     "prompt_override": args.prompt}]
        new, _ = mutate(store, fn)
        out({"attempt_id": new[0]["attempt_id"]})
    elif args.action == "answer":
        text = Path(args.file).read_text(encoding="utf-8") if args.file else args.text
        if text is None:
            raise LearnError("give --file or --text")

        def fn(cfg, events, st):
            a = st["attempts"].get(args.id)
            if not a:
                raise LearnError(f"unknown attempt {args.id}")
            if a["answered_at"]:
                raise LearnError(f"attempt {args.id} already answered — duplicate refused")
            if a["abandoned"]:
                raise LearnError(f"attempt {args.id} was abandoned")
            store.answers.mkdir(exist_ok=True)
            p = store.answers / f"{args.id}.md"
            atomic_write(p, text)
            return [{"type": "attempt_answer", "attempt_id": args.id, "answered_at": iso(now_utc()),
                     "answer_file": p.name, "self": args.self_report, "assisted": args.assisted,
                     "artifacts": args.artifact or []}]
        mutate(store, fn)
        out({"answered": args.id})
    elif args.action == "abandon":
        def fn(cfg, events, st):
            a = st["attempts"].get(args.id)
            if not a:
                raise LearnError(f"unknown attempt {args.id}")
            if a["grade"]:
                raise LearnError("already graded")
            return [] if a["abandoned"] else [{"type": "attempt_abandon", "attempt_id": args.id}]
        mutate(store, fn)
        out({"abandoned": args.id})


def cmd_payload(store, args):
    """The only thing the blind assessor sees: prompt, frozen key/rubric/alternatives, verbatim answer, artifacts."""
    cfg, events, st = load(store)
    a = st["attempts"].get(args.id)
    if not a:
        raise LearnError(f"unknown attempt {args.id}")
    if not a["answered_at"]:
        raise LearnError("attempt has no answer yet")
    ans = (store.answers / a["answer_file"]).read_text(encoding="utf-8")
    start = next(e for e in events if e["type"] == "attempt_start" and e["attempt_id"] == args.id)
    answer_ev = next(e for e in events if e["type"] == "attempt_answer" and e["attempt_id"] == args.id)
    it = st["items"].get(a["item_id"]) if a["item_id"] else None
    payload = {"attempt_id": args.id,
               "prompt": start.get("prompt_override") or (it or {}).get("prompt"),
               "key": (it or {}).get("key"), "rubric": (it or {}).get("rubric"),
               "accepted_alternatives": (it or {}).get("accepted_alternatives", []),
               "answer": ans, "artifacts": answer_ev.get("artifacts", []),
               "test_results": a["checks"]}
    if a["kind"] in CONCEPT_KINDS and args.key_file:
        payload.update(json.loads(Path(args.key_file).read_text(encoding="utf-8")))
    out(payload)


def cmd_grade(store, args):
    def fn(cfg, events, st):
        a = st["attempts"].get(args.id)
        if not a:
            raise LearnError(f"unknown attempt {args.id}")
        if not a["answered_at"]:
            raise LearnError("attempt has no recorded answer — record it with `attempt answer` first")
        if a["abandoned"]:
            raise LearnError("attempt was abandoned")
        prev = a["grade"]
        if prev and not args.regrade:
            raise LearnError(f"attempt already graded ({prev['outcome']}) — duplicate refused (use --regrade to supersede)")
        if args.regrade and not prev:
            raise LearnError("nothing to regrade")
        it = st["items"].get(a["item_id"]) if a["item_id"] else None
        if it and a["kind"] in FSRS_KINDS and a["item_rev"] != it["rev"] and not args.regrade:
            raise LearnError(f"stale attempt: item changed (rev {a['item_rev']} → {it['rev']}) — abandon and re-ask")
        if a["kind"] in FSRS_KINDS and a["checks"] and a["checks"][-1]["result"] == "infra_error" and args.outcome != "ungradable":
            raise LearnError("last test run was an infrastructure error — fix the runner or grade ungradable")
        rating = rating_for(args.outcome, a["assisted"], a["self"])
        area = st["concepts"][a["concept_id"]]["area"]
        ev = {"type": "grade", "attempt_id": args.id, "item_id": a["item_id"], "outcome": args.outcome,
              "rating": rating, "grader": args.grader, "note": args.note, "misconception": args.misconception,
              "config_version": cfg["current_version"], "retention": retention_for(cfg, area),
              "kind": a["kind"]}
        if args.stage_tested is not None:
            ev["stage_tested"] = args.stage_tested
        if prev:
            ev["supersedes"] = prev["id"]
        evs = [ev]
        # leech → suspend
        if it and a["kind"] in FSRS_KINDS and rating == "again" and it["lapses"] + 1 >= LEECH_LAPSES \
                and it["state"] == "active" and not prev:
            evs.append({"type": "item_state", "item_id": it["item_id"], "state": "suspended",
                        "reason": f"leech: {it['lapses'] + 1} lapses — needs a teach pass on its prerequisites"})
        return evs

    new, st = mutate(store, fn)
    a = st["attempts"][args.id]
    res = {"attempt": args.id, "outcome": args.outcome, "rating": new[0]["rating"]}
    if a["item_id"]:
        it = st["items"][a["item_id"]]
        cfg = store.config()
        ed = effective_due(it, cfg)
        res.update(next_due=iso(ed) if ed else None, item_state=it["state"],
                   next_due_local=ed.astimezone(tz(cfg)).strftime("%a %d %b %H:%M") if ed else None)
    c = st["concepts"][a["concept_id"]]
    res["concept_stage"] = STAGES[c["stage"]]
    if len(new) > 1:
        res["suspended"] = new[1]["reason"]
    out(res)


def cmd_queue(store, args):
    cfg, events, st = load(store)
    q, used, notes = build_queue(st, cfg, args.mode, args.minutes, args.seed)
    rows = []
    for it in q:
        c = st["concepts"][it["concept_id"]]
        rows.append({"item_id": it["item_id"], "type": it["type"], "area": c["area"], "concept": c["name"],
                     "family": it.get("family"), "new": it["reviews"] == 0,
                     "stage": STAGES[c["stage"]], "est_min": minutes_for(it, st, cfg), "prompt": it.get("prompt")})
    res = {"mode": args.mode, "items": rows, "est_minutes": round(used, 1), "notes": notes}
    pend = [a["attempt_id"] for a in st["attempts"].values() if a["answered_at"] and not a["grade"] and not a["abandoned"]]
    if pend:
        res["pending_grades"] = pend
    teach = [c["name"] for c in st["concepts"].values()
             if any(it["concept_id"] == c["concept_id"] and it["state"] == "needs_teaching" for it in st["items"].values())]
    if teach:
        res["teach_next"] = teach[:5]
    if checkpoint_due(st, cfg, now_utc()):
        res["checkpoint_due"] = True
    out(res)


def checkpoint_due(st, cfg, at) -> bool:
    eligible = checkpoint_eligible(st, cfg, at)
    if len(eligible) < 4:
        return False
    if not st["checkpoints"]:
        return True
    last = max(parse_ts(c["ts"]) for c in st["checkpoints"])
    return (at - last).days >= cfg["checkpoint_every_days"]


def checkpoint_eligible(st, cfg, at):
    age = timedelta(days=cfg["checkpoint_min_age_days"])
    def learned(it):
        # migrated items keep the date they were first learned in v2; others count from activation
        if it.get("learned_at"):
            return datetime.fromisoformat(it["learned_at"]).replace(tzinfo=timezone.utc)
        return parse_ts(it["activated"])
    return [it for it in st["items"].values()
            if it["state"] in ("active", "suspended") and it["activated"] and learned(it) <= at - age]


def cmd_checkpoint(store, args):
    """Queue-independent stratified random sample: all items first learned ≥ N days ago, whatever their last review."""
    def fn(cfg, events, st):
        at = now_utc()
        el = checkpoint_eligible(st, cfg, at)
        rng = random.Random(args.seed if args.seed is not None else int(at.timestamp()))
        by_area = {}
        for it in sorted(el, key=lambda i: i["item_id"]):
            by_area.setdefault(st["concepts"][it["concept_id"]]["area"], []).append(it)
        sample = []
        areas = sorted(by_area)
        per = max(1, args.n // max(1, len(areas))) if areas else 0
        for ar in areas:
            pool = by_area[ar][:]
            rng.shuffle(pool)
            sample += pool[:per]
        rest = [it for it in el if it not in sample]
        rng.shuffle(rest)
        sample += rest[: max(0, args.n - len(sample))]
        sid = new_id("cp")
        return [{"type": "checkpoint_session", "session_id": sid, "sampled": [i["item_id"] for i in sample],
                 "eligible": len(el), "baseline": args.baseline}]
    new, st = mutate(store, fn)
    ev = new[0]
    out({"session_id": ev["session_id"], "eligible": ev["eligible"], "sampled": ev["sampled"],
         "note": "start each with `attempt start --item <id> --kind checkpoint --session <session_id>`; "
                 "add 2–3 unseen matched problems per course as `--kind transfer --concept <id>`. No AI help, timed."
         if ev["sampled"] else "too few eligible items for a checkpoint yet — that is a valid result"})


def cmd_due(store, args):
    """Fast path for the SessionStart hook: reads only state.json, never imports fsrs, never fails loudly."""
    if args.brief:
        try:
            st = json.loads(store.state_path.read_text(encoding="utf-8"))
            at = now_utc()
            cfg = {"timezone": st.get("timezone", "Europe/Vienna"), "rollover_hour": st.get("rollover_hour", 4)}
            end = day_end_utc(local_day(at, cfg), cfg)
            est = st.get("est_minutes", {})
            due = [v for v in st["items"].values() if v["state"] == "active" and v["due"] and parse_ts(v["due"]) <= end
                   and v["reviews"] > 0]
            mins = sum(est.get(v["type"], 3) for v in due)
            parts = []
            if due:
                parts.append(f"{len(due)} review(s) due (~{mins:.0f} min)")
            if st.get("checkpoint_due"):
                parts.append("checkpoint due")
            if st.get("pending"):
                parts.append(f"{len(st['pending'])} answer(s) awaiting a grade")
            unfinished = [l for l in st.get("lessons", {}).values() if not l.get("finalized")]
            if unfinished:
                parts.append(f"{len(unfinished)} unfinished lesson(s)")
            if parts:
                print("📚 " + " · ".join(parts) + " — /tutor")
        except Exception:
            pass
        return
    cfg, events, st = load(store)
    q, used, notes = build_queue(st, cfg, "due", budget=10_000)
    out({"due_or_new_today": len(q), "est_minutes": round(used, 1), "notes": notes})


