def cmd_item_add(store, args):
    spec = json.loads(Path(args.json).read_text(encoding="utf-8")) if args.json else {}
    specs = spec if isinstance(spec, list) else [spec]

    def fn(cfg, events, st):
        evs = []
        for sp in specs:
            cid = sp.get("concept_id") or args.concept
            if cid not in st["concepts"]:
                raise LearnError(f"unknown concept {cid!r} — add it first with `concept add`")
            typ = sp.get("type", args.type or "concept")
            state = sp.get("state", "draft")
            if state == "active":
                problems = activation_problems({**sp, "item_type": typ})
                if problems:
                    raise LearnError(f"cannot add as active: {problems}")
            if sp.get("spawned_from"):
                if any(it.get("spawned_from") == sp["spawned_from"] for it in st["items"].values()) or \
                   any(e.get("spawned_from") == sp["spawned_from"] for e in evs):
                    raise LearnError(f"a mistake item already exists for {sp['spawned_from']} (max 1)")
            ev = {"type": "item_add", "item_id": sp.get("item_id") or new_id("i"), "concept_id": cid,
                  "item_type": typ, "state": state}
            for k in ITEM_FIELDS:
                if k in sp:
                    ev[k] = sp[k]
            ev.setdefault("area", st["concepts"][cid]["area"])
            evs.append(ev)
        return evs

    new, _ = mutate(store, fn)
    out({"added": [e["item_id"] for e in new]})


def activation_problems(it) -> str | None:
    missing = [k for k in ("prompt", "key", "rubric") if not str(it.get(k) or "").strip()]
    if missing:
        return f"missing {', '.join(missing)}"
    if not it.get("verified"):
        return "key not verified (set verified: {by, sources, date} after checking the key)"
    if it.get("item_type", it.get("type")) == "problem" and it.get("tests"):
        if not it["tests"].get("reference_passed") or not it["tests"].get("stub_failed"):
            return "code tests not validated (run `check-item` so the reference passes and a stub fails)"
    return None


