def cmd_refit(store, args):
    cfg, events, st = load(store)
    rows = []
    for ev in events:
        if ev["type"] != "grade" or ev.get("kind") not in FSRS_KINDS:
            continue
        a = st["attempts"][ev["attempt_id"]]
        if a["assisted"] or not a["grade"] or a["grade"]["id"] != ev["id"] or ev["rating"] == "none":
            continue
        rows.append(ev)
    n = len(rows)
    if n < 1000:
        out({"eligible_reviews": n, "needed": 1000, "action": "keep FSRS-6 defaults"})
        return
    try:
        from fsrs import Optimizer, ReviewLog, Rating  # needs `uv run --with "fsrs[optimizer]==6.3.2"`
    except ImportError:
        raise LearnError('optimizer not installed: rerun with  uv run --with "fsrs[optimizer]==6.3.2" learn.py refit')
    rmap = {"again": Rating.Again, "hard": Rating.Hard, "good": Rating.Good, "easy": Rating.Easy}
    logs = []
    for ev in rows:
        a = st["attempts"][ev["attempt_id"]]
        logs.append(ReviewLog(card_id=int(hashlib.sha1(a["item_id"].encode()).hexdigest()[:12], 16),
                              rating=rmap[ev["rating"]], review_datetime=parse_ts(a["answered_at"]),
                              review_duration=None))
    logs.sort(key=lambda l: l.review_datetime)
    cut = int(len(logs) * 0.8)
    train, hold = logs[:cut], logs[cut:]
    new_params = Optimizer(train).compute_optimal_parameters()
    cur = next(v["parameters"] for v in cfg["config_versions"] if v["version"] == cfg["current_version"])
    loss_old = Optimizer(hold)._compute_batch_loss(parameters=cur) if hasattr(Optimizer, "_compute_batch_loss") else None
    loss_new = Optimizer(hold)._compute_batch_loss(parameters=new_params) if loss_old is not None else None
    if loss_old is None or loss_new >= loss_old:
        out({"adopted": False, "holdout_logloss_old": loss_old, "holdout_logloss_new": loss_new})
        return
    with store.lock():
        cfg = store.config()
        v = max(x["version"] for x in cfg["config_versions"]) + 1
        cfg["config_versions"].append({"version": v, "parameters": list(new_params), "created": iso(now_utc()),
                                       "note": f"refit on {len(train)} reviews; holdout {loss_old:.4f}→{loss_new:.4f}"})
        cfg["current_version"] = v
        store.write_config(cfg)
    out({"adopted": True, "config_version": v})


