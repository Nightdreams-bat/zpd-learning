# ----------------------------------------------------------------------------- time

def now_utc() -> datetime:
    fake = os.environ.get("LEARN_NOW")
    if fake:
        return parse_ts(fake)
    return datetime.now(timezone.utc).replace(microsecond=0)


def parse_ts(s: str) -> datetime:
    d = datetime.fromisoformat(s.replace("Z", "+00:00"))
    if d.tzinfo is None:
        raise LearnError(f"timestamp without timezone: {s}")
    return d.astimezone(timezone.utc)


def iso(d: datetime) -> str:
    return d.astimezone(timezone.utc).isoformat().replace("+00:00", "Z")


def tz(cfg) -> "ZoneInfo":
    return ZoneInfo(cfg.get("timezone", "Europe/Vienna"))


def local_day(d: datetime, cfg) -> date:
    """The learner's 'day': local date with the day rolling over at rollover_hour (04:00)."""
    return (d.astimezone(tz(cfg)) - timedelta(hours=cfg.get("rollover_hour", 4))).date()


def day_end_utc(day: date, cfg) -> datetime:
    """UTC instant at which local `day` ends (next day's rollover hour, local time)."""
    nxt = datetime(day.year, day.month, day.day, cfg.get("rollover_hour", 4), tzinfo=tz(cfg)) + timedelta(days=1)
    # re-anchor to wall clock (timedelta on aware datetimes keeps the offset; rebuild for DST)
    nxt = datetime(nxt.year, nxt.month, nxt.day, cfg.get("rollover_hour", 4), tzinfo=tz(cfg))
    return nxt.astimezone(timezone.utc)


