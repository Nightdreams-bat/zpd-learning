DEFAULT_CONFIG = {
    "schema": SCHEMA,
    "timezone": "Europe/Vienna",
    "rollover_hour": 4,
    "budget_minutes": {"due": 15, "quick": 5, "problems": 20},
    "new_per_day": 10,
    "est_minutes": {"fact": 1, "concept": 2, "problem": 8, "mistake": 5},
    "default_retention": 0.90,
    "area_retention": {},
    "checkpoint_every_days": 14,
    "checkpoint_min_age_days": 14,
    "exam_cap_ratio": 0.2,
    "courses": {},  # name -> {"area":..., "exams":["YYYY-MM-DD"], "week1":"YYYY-MM-DD"}
    "config_versions": [],  # [{"version":1,"parameters":[...],"created":ts,"note":...}]
    "current_version": 0,
}


class Store:
    def __init__(self, vault: Path):
        self.vault = vault
        self.dir = vault / ".learn"
        self.events_path = self.dir / "events.jsonl"
        self.config_path = self.dir / "config.json"
        self.state_path = self.dir / "state.json"
        self.answers = self.dir / "answers"
        self.lock_path = self.dir / "lock"
        self._lock_held = False

    # -- existence
    def require(self):
        if not self.vault.exists():
            raise LearnError(f"vault not found: {self.vault} (is the drive mounted?) — not falling back anywhere")
        if not self.config_path.exists():
            raise LearnError(f"not initialised: run `learn.py init` (looked in {self.dir})")

    # -- config
    def config(self) -> dict:
        with open(self.config_path, encoding="utf-8") as f:
            cfg = json.load(f)
        merged = json.loads(json.dumps(DEFAULT_CONFIG))
        merged.update(cfg)
        return merged

    def write_config(self, cfg: dict):
        atomic_write(self.config_path, json.dumps(cfg, indent=2, ensure_ascii=False))

    # -- events
    def read_events(self) -> list[dict]:
        if not self.events_path.exists():
            return []
        raw = self.events_path.read_bytes()
        if raw and not raw.endswith(b"\n"):
            raise LearnError(
                "events.jsonl ends with an incomplete line (a write was interrupted). "
                "Run `learn.py doctor --fix-trailing` to drop that one partial line."
            )
        events = []
        for n, line in enumerate(raw.decode("utf-8").splitlines(), 1):
            if not line.strip():
                continue
            try:
                ev = json.loads(line)
            except json.JSONDecodeError as e:
                raise LearnError(f"events.jsonl line {n} is not valid JSON ({e}). Refusing to continue; see `learn.py doctor`.")
            problem = validate_event(ev)
            if problem:
                raise LearnError(f"events.jsonl line {n}: {problem}. Refusing to continue; see `learn.py doctor`.")
            events.append(ev)
        return events

    def append(self, events: list[dict]):
        assert self._lock_held, "append without lock"
        for ev in events:
            ev.setdefault("id", new_id("e"))
            ev.setdefault("ts", iso(now_utc()))
            problem = validate_event(ev)
            if problem:
                raise LearnError(f"refusing to write invalid event: {problem}")
        data = "".join(json.dumps(ev, ensure_ascii=False, sort_keys=True) + "\n" for ev in events)
        with open(self.events_path, "ab") as f:
            f.write(data.encode("utf-8"))
            f.flush()
            os.fsync(f.fileno())

    # -- lock
    def lock(self, timeout=10.0):
        return _Lock(self, timeout)


class _Lock:
    def __init__(self, store: Store, timeout: float):
        self.s, self.timeout = store, timeout

    def __enter__(self):
        deadline = time.monotonic() + self.timeout
        while True:
            try:
                fd = os.open(self.s.lock_path, os.O_CREAT | os.O_EXCL | os.O_WRONLY)
                os.write(fd, f"{os.getpid()} {iso(now_utc())}".encode())
                os.close(fd)
                self.s._lock_held = True
                return self.s
            except FileExistsError:
                # a lock older than 5 minutes is from a crashed process
                try:
                    if time.time() - self.s.lock_path.stat().st_mtime > 300:
                        self.s.lock_path.unlink(missing_ok=True)
                        continue
                except FileNotFoundError:
                    continue
                if time.monotonic() > deadline:
                    raise LearnError("busy: another session is writing (lock held). Retry in a moment.")
                time.sleep(0.1)

    def __exit__(self, *exc):
        self.s._lock_held = False
        self.s.lock_path.unlink(missing_ok=True)


def atomic_write(path: Path, text: str):
    path.parent.mkdir(parents=True, exist_ok=True)
    fd, tmp = tempfile.mkstemp(dir=path.parent, prefix=path.name + ".", suffix=".tmp")
    with os.fdopen(fd, "w", encoding="utf-8", newline="\n") as f:
        f.write(text)
        f.flush()
        os.fsync(f.fileno())
    os.replace(tmp, path)


def new_id(prefix: str) -> str:
    return f"{prefix}-{uuid.uuid4().hex[:10]}"


REQUIRED = {
    "concept_add": ["concept_id", "area", "name"],
    "concept_update": ["concept_id"],
    "item_add": ["item_id", "concept_id", "item_type", "state"],
    "item_revise": ["item_id", "fields"],
    "item_state": ["item_id", "state"],
    "lesson_start": ["lesson_id", "area", "path"],
    "lesson_finalize": ["lesson_id"],
    "formative": ["concept_id", "outcome"],
    "attempt_start": ["attempt_id", "concept_id", "kind"],
    "attempt_answer": ["attempt_id", "answered_at"],
    "attempt_abandon": ["attempt_id"],
    "grade": ["attempt_id", "outcome", "rating"],
    "check": ["attempt_id", "result"],
    "checkpoint_session": ["session_id", "sampled"],
}


def validate_event(ev) -> str | None:
    if not isinstance(ev, dict):
        return "event is not an object"
    t = ev.get("type")
    if t not in REQUIRED:
        return f"unknown event type {t!r}"
    for k in ["id", "ts"] + REQUIRED[t]:
        if k not in ev:
            return f"{t} event missing field {k!r}"
    try:
        parse_ts(ev["ts"])
    except Exception:
        return f"bad ts {ev.get('ts')!r}"
    if t == "grade" and ev["outcome"] not in ("correct", "incorrect", "ungradable"):
        return f"bad outcome {ev['outcome']!r}"
    if t == "attempt_start" and ev["kind"] not in ALL_KINDS:
        return f"bad attempt kind {ev['kind']!r}"
    if t in ("item_add", "item_state") and ev["state"] not in ITEM_STATES:
        return f"bad item state {ev['state']!r}"
    if t == "item_add" and ev["item_type"] not in ITEM_TYPES:
        return f"bad item type {ev['item_type']!r}"
    return None


# ----------------------------------------------------------------------------- scheduler

def scheduler_for(cfg, version: int, retention: float):
    from fsrs import Scheduler

    params = None
    for v in cfg["config_versions"]:
        if v["version"] == version:
            params = v["parameters"]
    if params is None:
        raise LearnError(f"unknown config_version {version}")
    return Scheduler(parameters=tuple(params), desired_retention=retention,
                     learning_steps=(), relearning_steps=(), enable_fuzzing=False)


def retention_for(cfg, area: str) -> float:
    return float(cfg["area_retention"].get(area, cfg["default_retention"]))


def rating_for(outcome: str, assisted: bool, self_report: str | None) -> str:
    """Grader decides correctness; effort comes only from the learner's pre-verdict self-report."""
    if outcome == "ungradable":
        return "none"
    if outcome == "incorrect" or assisted:
        return "again"
    if self_report == "struggled":
        return "hard"
    if self_report == "instant":
        return "easy"
    return "good"


# ----------------------------------------------------------------------------- replay

def replay(events: list[dict], cfg: dict) -> dict:
    """Fold the event log into current state. Pure and deterministic."""
    from fsrs import Card, Rating

    concepts, items, lessons, attempts = {}, {}, {}, {}
    checkpoints = []
    superseded = {ev["supersedes"] for ev in events if ev["type"] == "grade" and ev.get("supersedes")}
    rmap = {"again": Rating.Again, "hard": Rating.Hard, "good": Rating.Good, "easy": Rating.Easy}

    for ev in events:
        t = ev["type"]
        if t == "concept_add":
            concepts[ev["concept_id"]] = {
                "concept_id": ev["concept_id"], "area": ev["area"], "name": ev["name"],
                "lesson": ev.get("lesson"), "stage": int(ev.get("stage", 0)), "legacy": ev.get("legacy"),
                "formative_pass": bool(ev.get("legacy") and int(ev.get("stage", 0)) >= 2),
                "passes": [], "errors": [], "created": ev["ts"],
            }
        elif t == "concept_update":
            c = concepts[ev["concept_id"]]
            for k in ("name", "lesson", "area"):
                if k in ev:
                    c[k] = ev[k]
            if "stage" in ev:
                c["stage"] = int(ev["stage"])
        elif t == "item_add":
            it = {k: v for k, v in ev.items() if k not in ("type", "id", "ts")}
            it["type"] = ev["item_type"]
            it.setdefault("rev", 1)
            it.update(card=None, reviews=0, lapses=0, last_review=None, activated=None,
                      history=[], created=ev["ts"])
            items[ev["item_id"]] = it
            if ev["state"] == "active":
                _activate(it, ev["ts"], cfg)
        elif t == "item_revise":
            it = items[ev["item_id"]]
            it.update(ev["fields"])
            it["rev"] = it.get("rev", 1) + 1
        elif t == "item_state":
            it = items[ev["item_id"]]
            it["state"] = ev["state"]
            it["state_reason"] = ev.get("reason")
            if ev["state"] == "active" and it["activated"] is None:
                _activate(it, ev["ts"], cfg)
        elif t == "lesson_start":
            lessons[ev["lesson_id"]] = {"lesson_id": ev["lesson_id"], "area": ev["area"], "path": ev["path"],
                                        "started": ev["ts"], "finalized": None}
        elif t == "lesson_finalize":
            if ev["lesson_id"] in lessons:
                lessons[ev["lesson_id"]]["finalized"] = ev["ts"]
        elif t == "formative":
            c = concepts[ev["concept_id"]]
            if ev["outcome"] == "correct":
                c["formative_pass"] = True
                if c["stage"] < 1:
                    c["stage"] = 1
            else:
                c["errors"].append({"ts": ev["ts"], "note": ev.get("note", ""), "kind": "formative"})
        elif t == "attempt_start":
            attempts[ev["attempt_id"]] = {
                "attempt_id": ev["attempt_id"], "item_id": ev.get("item_id"), "concept_id": ev["concept_id"],
                "kind": ev["kind"], "item_rev": ev.get("item_rev"), "started_at": ev["ts"],
                "session": ev.get("session"), "answered_at": None, "abandoned": False,
                "grade": None, "self": None, "assisted": False, "checks": [],
            }
        elif t == "attempt_answer":
            a = attempts[ev["attempt_id"]]
            a.update(answered_at=ev["answered_at"], self=ev.get("self"), assisted=bool(ev.get("assisted")),
                     answer_file=ev.get("answer_file"))
        elif t == "attempt_abandon":
            attempts[ev["attempt_id"]]["abandoned"] = True
        elif t == "check":
            attempts[ev["attempt_id"]]["checks"].append({"result": ev["result"], "ts": ev["ts"]})
        elif t == "checkpoint_session":
            checkpoints.append({"session_id": ev["session_id"], "ts": ev["ts"], "sampled": ev["sampled"],
                                "eligible": ev.get("eligible")})
        elif t == "grade":
            a = attempts[ev["attempt_id"]]
            if ev["id"] in superseded:
                continue
            a["grade"] = {k: ev.get(k) for k in ("id", "outcome", "rating", "note", "misconception", "grader")}
            a["grade"]["ts"] = ev["ts"]
            c = concepts.get(a["concept_id"])
            when = parse_ts(a["answered_at"] or ev["ts"])
            ok = ev["outcome"] == "correct" and not a["assisted"]
            if ev["outcome"] == "ungradable":
                continue
            # FSRS update (items only, scheduled/checkpoint kinds)
            if a["kind"] in FSRS_KINDS and a["item_id"]:
                it = items[a["item_id"]]
                sch = scheduler_for(cfg, ev["config_version"], ev["retention"])
                card = Card.from_dict(it["card"]) if it["card"] else _new_card(it, cfg)
                elapsed = (when - parse_ts(it["last_review"])).days if it["last_review"] else None
                card, _ = sch.review_card(card, rmap[ev["rating"]], when)
                it["card"] = card.to_dict()
                it["reviews"] += 1
                it["last_review"] = iso(when)
                if ev["rating"] == "again":
                    it["lapses"] += 1
                it["history"].append({"ts": iso(when), "rating": ev["rating"], "kind": a["kind"],
                                      "elapsed_days": elapsed, "ok": ok})
            # concept stage
            if c is not None:
                _stage_update(c, a, ok, ev, when, cfg)
    return {"concepts": concepts, "items": items, "lessons": lessons, "attempts": attempts,
            "checkpoints": checkpoints}


def _new_card(it, cfg):
    from fsrs import Card

    return Card(card_id=int(hashlib.sha1(it["item_id"].encode()).hexdigest()[:12], 16),
                due=parse_ts(it["activated"]))


def _activate(it, ts, cfg):
    """First review is a delayed free recall: due at the end of the activation day (≥ next rollover)."""
    it["activated"] = iso(day_end_utc(local_day(parse_ts(ts), cfg), cfg))
    it["state"] = "active"


def _stage_update(c, a, ok, ev, when, cfg):
    stage_tested = ev.get("stage_tested")
    if stage_tested is None:
        stage_tested = {"variant": 3, "apply": 4, "transfer": 4, "probe": 2}.get(a["kind"], max(c["stage"], 2))
    if ok:
        src = a["item_id"] or a["attempt_id"]
        c["passes"].append((src, local_day(when, cfg).isoformat(), a["kind"]))
        if c["stage"] < 2 and c["formative_pass"] and a["kind"] in FSRS_KINDS:
            c["stage"] = 2
        if c["stage"] == 2:
            days_by_src = {}
            for s, d, k in c["passes"]:
                if k in FSRS_KINDS + ("variant", "apply", "transfer"):
                    days_by_src.setdefault(s, set()).add(d)
            srcs = list(days_by_src)
            # >=2 different items/variants, passed on >=2 different days
            all_days = set().union(*days_by_src.values()) if days_by_src else set()
            if len(srcs) >= 2 and len(all_days) >= 2:
                c["stage"] = 3
        if c["stage"] >= 3 and a["kind"] in ("apply", "transfer"):
            c["stage"] = 4
    else:
        c["errors"].append({"ts": iso(when), "note": ev.get("misconception") or ev.get("note") or "",
                            "kind": a["kind"]})
        if stage_tested <= c["stage"] and c["stage"] > 1:
            c["stage"] -= 1


# ----------------------------------------------------------------------------- derived views

def effective_due(it, cfg) -> datetime | None:
    if it.get("state") != "active":
        return None
    due = parse_ts(it["card"]["due"]) if it["card"] else parse_ts(it["activated"])
    exam = next_exam_for(it, cfg, parse_ts(it["last_review"]) if it["last_review"] else None)
    if exam and it["last_review"]:
        last = parse_ts(it["last_review"])
        days_left = max(0.0, (exam - last).total_seconds() / 86400)
        cap = last + timedelta(days=max(1.0, cfg["exam_cap_ratio"] * days_left))
        if cap < due:
            due = cap
    return due


def next_exam_for(it, cfg, after: datetime | None) -> datetime | None:
    """Earliest exam, across the item's courses, that is after `after` (or after now)."""
    ref = after or now_utc()
    best = None
    courses = it.get("courses") or ([it["course"]] if it.get("course") else [])
    for name in courses:
        for d in cfg["courses"].get(name, {}).get("exams", []):
            ex = datetime.fromisoformat(d).replace(hour=9, tzinfo=tz(cfg)).astimezone(timezone.utc)
            if ex > ref and ex > now_utc() and (best is None or ex < best):
                best = ex
    return best


def retrievability(it, cfg, at: datetime) -> float:
    if not it["card"] or not it["last_review"]:
        return 0.0
    from fsrs import Card

    sch = scheduler_for(cfg, cfg["current_version"], retention_for(cfg, it.get("area", "")))
    return float(sch.get_card_retrievability(Card.from_dict(it["card"]), at))


def minutes_for(it, st, cfg) -> float:
    """Estimate from config, refined by the median observed answer time for that item type (≥5 samples)."""
    obs = []
    for a in st["attempts"].values():
        if a["answered_at"] and a["item_id"] and st["items"].get(a["item_id"], {}).get("type") == it["type"]:
            dur = (parse_ts(a["answered_at"]) - parse_ts(a["started_at"])).total_seconds() / 60
            if 0 < dur <= 45:
                obs.append(dur)
    if len(obs) >= 5:
        obs.sort()
        return round(obs[len(obs) // 2], 1)
    return float(cfg["est_minutes"].get(it["type"], 3))


def build_queue(st, cfg, mode="due", budget=None, seed=None, at=None):
    at = at or now_utc()
    today = local_day(at, cfg)
    end = day_end_utc(today, cfg)
    budget = float(budget if budget is not None else cfg["budget_minutes"].get(mode, 15))
    items = [it for it in st["items"].values() if it["state"] == "active"]
    if mode == "problems":
        items = [it for it in items if it["type"] in ("problem", "mistake")]
    # items with an open (answered, ungraded) attempt are not re-served
    open_items = {a["item_id"] for a in st["attempts"].values()
                  if a["item_id"] and a["answered_at"] and not a["grade"] and not a["abandoned"]}
    due, new = [], []
    for it in items:
        if it["item_id"] in open_items:
            continue
        ed = effective_due(it, cfg)
        if it["reviews"] == 0:
            if ed <= end:
                new.append(it)
        elif ed <= end:
            due.append(it)
    due.sort(key=lambda it: (retrievability(it, cfg, at), it["item_id"]))
    chosen, used, notes = [], 0.0, []
    for it in due:
        m = minutes_for(it, st, cfg)
        if used + m > budget and chosen:
            break
        chosen.append(it)
        used += m
    overflow_due = len(due) - len(chosen)
    if overflow_due > 0:
        notes.append(f"{overflow_due} more due item(s) left for the next session (lowest-recall first today)")
    # admission control for never-reviewed items
    introduced_today = sum(1 for it in st["items"].values() if it["history"] and
                           local_day(parse_ts(it["history"][0]["ts"]), cfg) == today)
    new_cap = max(0, cfg["new_per_day"] - introduced_today)
    load = projected_load_minutes(st, cfg, at)
    daily_budget = float(cfg["budget_minutes"].get("due", 15))
    if load > daily_budget:
        if new:
            notes.append(f"new items paused: projected review load {load:.0f} min/day > budget {daily_budget:.0f}")
        new_cap = 0
    new.sort(key=lambda it: (it["activated"], it["item_id"]))
    for it in new[:new_cap]:
        m = minutes_for(it, st, cfg)
        if used + m > budget and chosen:
            break
        chosen.append(it)
        used += m
    chosen = older_week_quota(chosen, items, st, cfg, notes) if mode == "problems" else chosen
    ordered = interleave(chosen, seed)
    return ordered, used, notes


def projected_load_minutes(st, cfg, at) -> float:
    end = at + timedelta(days=7)
    total = 0.0
    for it in st["items"].values():
        if it["state"] == "active" and it["reviews"] > 0:
            ed = effective_due(it, cfg)
            if ed and ed <= end:
                total += minutes_for(it, st, cfg)
    return total / 7


def older_week_quota(chosen, pool, st, cfg, notes):
    """In problems mode aim for 30–50% of problems from earlier course weeks (Rohrer)."""
    weekly = [it for it in chosen if it.get("course") and it.get("week") is not None]
    if not weekly:
        return chosen
    cur = {}
    for it in pool:
        if it.get("course") and it.get("week") is not None:
            cur[it["course"]] = max(cur.get(it["course"], 0), int(it["week"]))
    older = [it for it in chosen if it.get("week") is not None and int(it["week"]) < cur.get(it.get("course"), 0)]
    share = len(older) / len(chosen)
    if share < 0.3:
        spare = [it for it in pool if it not in chosen and it.get("week") is not None
                 and int(it["week"]) < cur.get(it.get("course"), 0) and it["reviews"] > 0]
        spare.sort(key=lambda it: it["item_id"])
        need = max(1, round(0.3 * len(chosen)) - len(older))
        if len(spare) < need:
            notes.append("older-week quota (30%) not reachable: not enough earlier-week problems yet")
        chosen = chosen + spare[:need]
    return chosen


def interleave(items, seed=None):
    """Order the session: word-list facts stay grouped (blocking wins for words); everything else is
    shuffled, then greedily re-ordered so the same problem family / tag is never back to back when an
    alternative exists, alternating competing families within a course."""
    rng = random.Random(seed)
    blocks = {}
    rest = []
    for it in items:
        wl = next((t for t in it.get("tags", []) if t.startswith("wordlist:")), None)
        if wl:
            blocks.setdefault(wl, []).append(it)
        else:
            rest.append(it)
    rng.shuffle(rest)
    key = lambda it: it.get("family") or (it.get("tags") or [None])[0] or it["concept_id"]
    out, prev = [], None
    pool = rest[:]
    while pool:
        pick = next((it for it in pool if key(it) != prev and (not out or it.get("course") == out[-1].get("course"))), None)
        pick = pick or next((it for it in pool if key(it) != prev), pool[0])
        pool.remove(pick)
        out.append(pick)
        prev = key(pick)
    for name in sorted(blocks):
        out.extend(sorted(blocks[name], key=lambda it: it["item_id"]))
    return out


